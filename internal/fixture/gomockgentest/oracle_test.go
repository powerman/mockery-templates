package gomockgentest_test

import (
	"go/ast"
	"go/parser"
	"go/scanner"
	"go/token"
	"maps"
	"os"
	"slices"
	"strings"
	"testing"

	"github.com/powerman/check"
)

// sameCode lists replacements of token sequences which make equal code look the same.
var sameCode = [][2]string{
	// Trailing commas depend on line breaks.
	{", )", ")"},
	{", }", "}"},
	{", ]", "]"},
	// mockery prints the type interface{} as any.
	{"interface { }", "any"},
}

// goMockgenDivergences lists replacements of token sequences in go-mockgen output
// which result in the template output.
var goMockgenDivergences = [][2]string{
	// Type aliases are kept: fixture.Repo uses fixture.Ctx = context.Context.
	{"context . Context", "fixture . Ctx"},
}

// TestGoMockgen compares the template output with go-mockgen output for the same interfaces
// (generated by mise task oracle:go-mockgen).
// Each top-level declaration is compared as a sequence of tokens and comments,
// so their order, formatting and wrapping of comments are ignored.
func TestGoMockgen(tt *testing.T) {
	tt.Parallel()
	t := check.T(tt)

	got := parseDecls(t, "stub.fixture.go", sameCode)
	want := parseDecls(t, "testdata/go-mockgen.stub.fixture.go", sameCode, goMockgenDivergences)

	t.DeepEqual(slices.Sorted(maps.Keys(got)), slices.Sorted(maps.Keys(want)))
	for name, decl := range want {
		t.Equal(got[name], decl, name)
	}
}

// parseDecls returns normalized top-level declarations except imports,
// keyed by declaration name (Type or Type.Method).
func parseDecls(t *check.C, path string, replacements ...[][2]string) map[string]string {
	t.Helper()
	src, err := os.ReadFile(path)
	t.Must(t.Nil(err))
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	t.Must(t.Nil(err))

	decls := make(map[string]string)
	for _, decl := range file.Decls {
		var name string
		var doc *ast.CommentGroup
		switch decl := decl.(type) {
		case *ast.GenDecl:
			if decl.Tok != token.TYPE {
				continue
			}
			name, doc = decl.Specs[0].(*ast.TypeSpec).Name.Name, decl.Doc
		case *ast.FuncDecl:
			name, doc = decl.Name.Name, decl.Doc
			if decl.Recv != nil {
				name = recvTypeName(decl.Recv.List[0].Type) + "." + name
			}
		}
		start := decl.Pos()
		if doc != nil {
			start = doc.Pos()
		}
		begin, end := fset.Position(start).Offset, fset.Position(decl.End()).Offset
		tokens := scanTokens(src[begin:end])
		for _, r := range replacements {
			tokens = replaceTokens(tokens, r)
		}
		decls[name] = joinTokens(tokens)
	}
	return decls
}

func recvTypeName(expr ast.Expr) string {
	switch expr := expr.(type) {
	case *ast.StarExpr:
		return recvTypeName(expr.X)
	case *ast.IndexExpr:
		return recvTypeName(expr.X)
	case *ast.IndexListExpr:
		return recvTypeName(expr.X)
	case *ast.Ident:
		return expr.Name
	default:
		panic("unexpected receiver type")
	}
}

// scanTokens returns tokens without semicolons, because automatic ones depend on line breaks.
// Adjacent comments are joined into one token with normalized spaces.
func scanTokens(src []byte) []string {
	var s scanner.Scanner
	s.Init(token.NewFileSet().AddFile("", -1, len(src)), src, nil, scanner.ScanComments)
	var tokens []string
	for {
		_, tok, lit := s.Scan()
		switch {
		case tok == token.EOF:
			return tokens
		case tok == token.SEMICOLON:
		case tok == token.COMMENT:
			text := strings.Join(strings.Fields(strings.TrimPrefix(lit, "//")), " ")
			if last := len(tokens) - 1; last >= 0 && strings.HasPrefix(tokens[last], "//") {
				tokens[last] += " " + text
			} else {
				tokens = append(tokens, "// "+text)
			}
		case lit != "":
			tokens = append(tokens, lit)
		default:
			tokens = append(tokens, tok.String())
		}
	}
}

// replaceTokens applies replacements of space-separated token sequences in order.
func replaceTokens(tokens []string, replacements [][2]string) []string {
	for _, r := range replacements {
		from, to := strings.Fields(r[0]), strings.Fields(r[1])
		var res []string
		for i := 0; i < len(tokens); {
			if end := i + len(from); end <= len(tokens) && slices.Equal(tokens[i:end], from) {
				res = append(res, to...)
				i = end
			} else {
				res = append(res, tokens[i])
				i++
			}
		}
		tokens = res
	}
	return tokens
}

// joinTokens returns tokens separated by spaces,
// with line breaks around comments and inside braces to make a diff readable.
func joinTokens(tokens []string) string {
	var buf strings.Builder
	for i, tok := range tokens {
		switch {
		case i == 0:
		case strings.HasPrefix(tok, "//"), tok == "}", tokens[i-1] == "{",
			strings.HasPrefix(tokens[i-1], "//"):
			buf.WriteByte('\n')
		default:
			buf.WriteByte(' ')
		}
		buf.WriteString(tok)
	}
	return buf.String()
}
